using ll=long long ;
#define endl '\n'
#define int long long

void solve(){
    string arr;cin>>arr;
    int ans=0;
    if(arr[0]=='0') {cout<<"0"<<endl; return;}

    if(arr[0]=='?') ans=9;
    else ans=1;
    for(int i=1;i<arr.size();i++){
        if(arr[i]=='?'){
            ans=max(ans*10, 10*1LL);
        }
    }
    
    cout<<ans<<endl;
}

